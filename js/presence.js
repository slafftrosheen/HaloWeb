  function normalizedRows(name) {
    var rows = GLYPHS[name] || GLYPHS.halo;
    return rows.map(function (row) {
      if (row.length < 16) return (row + '................').slice(0,16);
      return row.slice(0,16);
    });
  }

  function glyphSvg(name) {
    var rows = normalizedRows(name);
    var rects = [];
    rows.forEach(function (row, y) {
      var x = 0;
      while (x < 16) {
        if (row.charAt(x) !== '█') { x++; continue; }
        var start = x;
        while (x < 16 && row.charAt(x) === '█') x++;
        rects.push('<rect x="' + start + '" y="' + y + '" width="' + (x-start) + '" height="1"/>');
      }
    });
    return '<svg viewBox="0 0 16 16" aria-hidden="true" focusable="false">' + rects.join('') + '</svg>';
  }

  function renderGlyph(el) {
    if (!el) return;
    var name = (el.getAttribute('data-glyph') || 'halo').toLowerCase();
    el.innerHTML = glyphSvg(name);
  }

  function renderGlyphs(root) {
    Array.prototype.forEach.call((root || document).querySelectorAll('.halo-glyph'), renderGlyph);
  }

  function SignalFace(el) {
    this.el = el;
    this.timer = 0;
    this.state = el.getAttribute('data-state') || 'ready';
    this.apply(this.state, false);
  }

  SignalFace.prototype.apply = function (state, animate) {
    var s = STATES[state] || STATES.ready;
    this.state = state;
    this.el.setAttribute('data-state', state);
    this.el.style.setProperty('--halo-a', s.a);
    this.el.style.setProperty('--halo-b', s.b);
    this.el.setAttribute('aria-label', 'Halo Signal Face, ' + s.label);
    var glyph = this.el.querySelector('.signal-glyph');
    if (glyph) {
      glyph.setAttribute('data-glyph', s.glyph);
      renderGlyph(glyph);
    }
    if (animate !== false) {
      this.el.classList.remove('is-switching');
      void this.el.offsetWidth;
      this.el.classList.add('is-switching');
      var self = this;
      window.setTimeout(function () { self.el.classList.remove('is-switching'); }, 340);
    }
  };

  SignalFace.prototype.burst = function () {
    window.clearTimeout(this.timer);
    this.el.classList.remove('is-bursting');
    void this.el.offsetWidth;
    this.el.classList.add('is-bursting');
    var self = this;
    this.timer = window.setTimeout(function () {
      self.el.classList.remove('is-bursting');
    }, 860);
  };

  SignalFace.prototype.setState = function (state) {
    this.apply(state, true);
    this.burst();
  };

  SignalFace.prototype.destroy = function () {
    window.clearTimeout(this.timer);
    this.el.classList.remove('is-bursting','is-switching');
  };

